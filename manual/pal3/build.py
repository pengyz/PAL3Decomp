# build.py - build logic (Python) + NMake Makefile generation
# Generates Makefile to build/ (out-of-tree), then runs nmake
# No manually maintained Makefile - all logic in Python
#
# [R110 修 2026-10-27] 病灶层三问（编译链整体修复）：
#   1. 病灶层：Makefile 生成层（build.py generate_makefile）——
#      NMAKE 在 wine 下经 cmd.exe 执行 recipe，历史 recipe 写了
#      Unix 结构 `cd build && wine Z:/.../LIB.EXE ...`（cd/wine/&&/正斜杠）
#      ⇒ U1077 fatal；另 env INCLUDE/LIB 用 os.pathsep(':') + Unix 路径，
#      cl/link 无法解析（当时靠 /I 侥幸编过）。
#   2. 消费者：NMAKE.EXE(wine→cmd.exe) 读 build/Makefile；cl/link/lib 读
#      env INCLUDE/LIB + /I 与显式 .lib 全路径。
#   3. 报错缺什么：U1077 只给 command 失败，不给"recipe 须 Windows 命令"；
#      修法 = recipe 一律 cmd.exe 可执行的 Windows 命令 + 全路径反斜杠。

import os
import platform
import shutil
import subprocess
import sys


def to_wine_path(p):
    """Unix 路径转 Wine Z: 格式（Linux wine 用）。

    [R110 修] 先 abspath 消掉 '..' 段（旧版 Z:\\a\\b\\..\\..\\x 形式
    经 cmd/nmake 解析易踩转义/大小写坑），再统一反斜杠。
    """
    p = os.path.abspath(p)
    if platform.system() == 'Linux':
        return 'Z:' + p.replace('/', '\\')
    return p  # Windows 直接用


def win_relpath(src, base):
    """src 相对 base 的 Windows 风格相对路径（recipe/依赖行用）。"""
    return os.path.relpath(src, base).replace('/', '\\')


def generate_makefile(build_dir, sources, gbengine_dir, include_dir, vc6_root, vc6_lib, vc6_include):
    """Generate NMake Makefile to build/ (auto from source collection)

    [R110 修] recipe 全部改为 cmd.exe 可执行的 Windows 命令：
      - gbengine.lib 用 $(LIBTOOL)（$(VC6_ROOT)\\Bin\\LIB.EXE），不再 cd/wine
      - 路径全反斜杠绝对形（to_wine_path 已 abspath）
      - 去掉重复的 $(TARGET) 空依赖规则（两处 $(TARGET) 规则合并为一处）
    """
    # [R109 修 2026-10-27] obj 镜像源相对路径（防同名碰撞）
    objs = []
    for s in sources:
        rel = os.path.relpath(s, os.path.join(gbengine_dir, '..', '..', 'manual', 'pal3'))
        obj_rel = os.path.splitext(rel)[0] + '.obj'
        obj_path = os.path.join(build_dir, obj_rel)
        os.makedirs(os.path.dirname(obj_path), exist_ok=True)
        objs.append(to_wine_path(obj_path))
    bdir = to_wine_path(build_dir)
    gdir = to_wine_path(gbengine_dir)

    makefile = f"""# Auto-generated by build.py (do not edit manually)
# Out-of-tree build - sources collected recursively
# NOTE: nmake runs under wine -> recipes MUST be plain Windows commands
#       (cmd.exe): no `cd x &&`, no `wine`, no forward-slash paths.

BUILD_DIR = {bdir}
GBENGINE_DIR = {gdir}
INCLUDE_DIR = {to_wine_path(include_dir)}
VC6_ROOT = {to_wine_path(vc6_root)}
VC6_LIB = {to_wine_path(vc6_lib)}
VC6_INCLUDE = {to_wine_path(vc6_include)}

CC = $(VC6_ROOT)\\Bin\\CL.EXE
LINK = $(VC6_ROOT)\\Bin\\LINK.EXE
LIBTOOL = $(VC6_ROOT)\\Bin\\LIB.EXE

CFLAGS = /W3 /GX /O2 /Zi /Ob2 /Oi /Ot /Oy /EHsc /I$(INCLUDE_DIR) /I$(INCLUDE_DIR)\\gbengine /I$(VC6_INCLUDE)
LFLAGS = /DEBUG /MAP /SUBSYSTEM:WINDOWS /OPT:NOREF

TARGET = $(BUILD_DIR)\\PAL3_manual.exe
GBENGINE_LIB = $(GBENGINE_DIR)\\gbengine.lib
LIBS = $(GBENGINE_LIB) $(VC6_LIB)\\user32.lib $(VC6_LIB)\\gdi32.lib $(VC6_LIB)\\winmm.lib $(VC6_LIB)\\uuid.lib $(VC6_LIB)\\ole32.lib $(VC6_LIB)\\oleaut32.lib $(VC6_LIB)\\advapi32.lib $(VC6_LIB)\\shell32.lib $(VC6_LIB)\\libc.lib $(VC6_LIB)\\oldnames.lib $(VC6_LIB)\\kernel32.lib

OBJS = {' '.join(objs)}

all: $(TARGET)

# [R110 修] gbengine.lib 自动生成（fresh clone 必须）：
# 纯 Windows 命令（nmake cwd 已是 build，但显式全路径不依赖 cwd）
$(GBENGINE_LIB): $(BUILD_DIR)\\gbengine.def
	$(LIBTOOL) /DEF:$(BUILD_DIR)\\gbengine.def /OUT:$(GBENGINE_LIB) /MACHINE:IX86

$(TARGET): $(OBJS) $(GBENGINE_LIB)
	$(LINK) $(LFLAGS) /OUT:$(TARGET) $(OBJS) $(LIBS)

"""
    # Add compile rules for each source
    for src, obj in zip(sources, objs):
        rel_src = win_relpath(src, build_dir)
        makefile += f"""{obj}: {rel_src}
	$(CC) $(CFLAGS) /Fo{obj} /c {rel_src}

"""
    # [R110 修] 去掉 .PHONY（NMAKE 不支持；旧版未报错但属 GNU 语法）
    makefile += """clean:
	-del /q $(BUILD_DIR)\\*.obj $(BUILD_DIR)\\*.exe 2>nul

"""
    makefile_path = os.path.join(build_dir, 'Makefile')
    with open(makefile_path, 'w') as f:
        f.write(makefile)
    return makefile_path


def main():
    src_dir = os.path.dirname(os.path.abspath(__file__))
    build_dir = os.path.join(src_dir, 'build')
    os.makedirs(build_dir, exist_ok=True)

    # Relative paths (no hardcoded absolute)
    # [R104 修 2026-10-27] 统一用游戏路径（与 L25 GBENGINE_DIR 一致）
    # [R107 修] 删硬编码游戏路径（gbengine.lib 在 build/ 生成）
    gbengine_dir = build_dir
    include_dir = os.path.join(src_dir, '..', '..', 'include')
    vc6_root = os.path.join(src_dir, '..', '..', 'tools', 'compilers', 'msvc6.0')
    vc6_lib = os.path.join(src_dir, '..', '..', 'tools', 'vc6', 'Lib')
    vc6_include = os.path.join(src_dir, '..', '..', 'tools', 'vc6', 'Include')

    # Recursive source collection (auto - no hardcoded subdirs)
    sources = []
    for root, dirs, files in os.walk(src_dir):
        # [R109 修 2026-10-27] 'build' 子串匹配 -> 精确匹配（防 checkout 路径含 build 断链）
        if 'build' in root.split(os.sep):
            continue
        for f in files:
            if f.endswith('.cpp'):
                sources.append(os.path.join(root, f))

    print('Sources: %d' % len(sources))

    # [R108 修] 复制 gbengine.def 到 build/（简化路径）
    def_src = os.path.join(src_dir, '..', '..', 'gbengine', 'gbengine.def')
    def_dst = os.path.join(build_dir, 'gbengine.def')
    if os.path.exists(def_src):
        shutil.copy2(def_src, def_dst)
    else:
        print('FATAL: gbengine.def not found: %s' % def_src)
        return 2

    makefile_path = generate_makefile(build_dir, sources, gbengine_dir, include_dir, vc6_root, vc6_lib, vc6_include)
    print('Makefile: %s' % makefile_path)

    # Run nmake (build/Makefile)
    # [R102 修 2026-10-27] 兼容 Linux wine / Windows 非 wine
    # Linux: wine NMAKE.EXE · Windows: NMAKE.EXE 直接
    nmake_path = os.path.join(vc6_root, 'Bin', 'NMAKE.EXE')
    if platform.system() == 'Linux':
        nmake = ['wine', nmake_path]
    else:
        nmake = [nmake_path]
    env = os.environ.copy()
    # [R110 修] INCLUDE/LIB 是 Windows 环境变量：分隔符必须是 ';'，
    # 条目必须是 Windows 路径（旧版 os.pathsep=':' + Unix 路径 ⇒ cl/link 解析失败）
    env['INCLUDE'] = ';'.join([
        to_wine_path(os.path.join(vc6_root, 'include')),
        to_wine_path(vc6_include),
        to_wine_path(include_dir),
        to_wine_path(os.path.join(include_dir, 'gbengine')),
    ])
    # [R105 修 2026-10-27] 加 Windows SDK 库路径（user32.lib 等）
    env['LIB'] = ';'.join([
        to_wine_path(os.path.join(vc6_root, 'lib')),
        to_wine_path(vc6_lib),  # Windows SDK 库（user32.lib/gdi32.lib 等）
        to_wine_path(gbengine_dir),
    ])

    result = subprocess.run(nmake + ['/f', 'Makefile'], cwd=build_dir, env=env)
    return result.returncode


if __name__ == '__main__':
    sys.exit(main())

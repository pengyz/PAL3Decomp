# build.py - build logic (Python) + NMake Makefile generation
# Generates Makefile to build/ (out-of-tree), then runs nmake
# No manually maintained Makefile - all logic in Python

import os
import subprocess
import sys

def generate_makefile(build_dir, sources, gbengine_dir, include_dir, vc6_root, vc6_lib, vc6_include):
    """Generate NMake Makefile to build/ (auto from source collection)"""
    objs = [os.path.join(build_dir, os.path.splitext(os.path.basename(s))[0] + '.obj') for s in sources]
    
    makefile = f"""# Auto-generated by build.py (do not edit manually)
# Out-of-tree build - sources collected recursively

BUILD_DIR = {build_dir}
GBENGINE_DIR = {gbengine_dir}
INCLUDE_DIR = {include_dir}
VC6_ROOT = {vc6_root}
VC6_LIB = {vc6_lib}
VC6_INCLUDE = {vc6_include}

CC = $(VC6_ROOT)\\bin\\cl.exe
LINK = $(VC6_ROOT)\\bin\\link.exe

CFLAGS = /W3 /GX /O2 /Ob2 /Oi /Ot /Oy /EHsc /I$(INCLUDE_DIR) /I$(INCLUDE_DIR)\\gbengine /I$(VC6_INCLUDE)
LFLAGS = /OPT:NOREF

TARGET = $(BUILD_DIR)\\PAL3_manual.exe
LIBS = $(GBENGINE_DIR)\\gbengine.lib user32.lib gdi32.lib winmm.lib

OBJS = {' '.join(objs)}

all: $(TARGET)

$(TARGET): $(OBJS)
	$(LINK) $(LFLAGS) /OUT:$(TARGET) $(OBJS) $(LIBS)

"""
    # Add compile rules for each source
    for src, obj in zip(sources, objs):
        rel_src = os.path.relpath(src, build_dir)
        makefile += f"""{obj}: {rel_src}
	$(CC) $(CFLAGS) /Fo$(BUILD_DIR)\\ /c {rel_src}

"""
    
    makefile += """clean:
	-del /q $(BUILD_DIR)\\*.obj $(BUILD_DIR)\\*.exe 2>nul

.PHONY: all clean
"""
    
    makefile_path = os.path.join(build_dir, 'Makefile')
    with open(makefile_path, 'w') as f:
        f.write(makefile)
    return makefile_path

def main():
    src_dir = os.path.dirname(os.path.abspath(__file__))
    build_dir = os.path.join(src_dir, 'build')
    os.makedirs(build_dir, exist_ok=True)

    # Relative paths (no hardcoded absolute)
    gbengine_dir = os.path.join(src_dir, '..', '..', 'gbengine')
    include_dir = os.path.join(src_dir, '..', '..', 'include')
    vc6_root = os.path.join(src_dir, '..', '..', 'tools', 'compilers', 'msvc6.0')
    vc6_lib = os.path.join(src_dir, '..', '..', 'tools', 'vc6', 'Lib')
    vc6_include = os.path.join(src_dir, '..', '..', 'tools', 'vc6', 'Include')

    # Recursive source collection (auto - no hardcoded subdirs)
    sources = []
    for root, dirs, files in os.walk(src_dir):
        if 'build' in root:
            continue
        for f in files:
            if f.endswith('.cpp'):
                sources.append(os.path.join(root, f))

    print('Sources: %d' % len(sources))

    # Generate Makefile (build/Makefile - auto)
    makefile_path = generate_makefile(build_dir, sources, gbengine_dir, include_dir, vc6_root, vc6_lib, vc6_include)
    print('Makefile: %s' % makefile_path)

    # Run nmake (build/Makefile)
    nmake = os.path.join(vc6_root, 'bin', 'nmake.exe')
    env = os.environ.copy()
    env['INCLUDE'] = os.pathsep.join([os.path.join(vc6_root, 'include'), vc6_include, include_dir, os.path.join(include_dir, 'gbengine')])
    env['LIB'] = os.pathsep.join([os.path.join(vc6_root, 'lib'), vc6_lib, gbengine_dir])
    
    result = subprocess.run([nmake, '/f', 'Makefile'], cwd=build_dir, env=env)
    return result.returncode

if __name__ == '__main__':
    sys.exit(main())

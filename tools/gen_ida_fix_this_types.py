#!/usr/bin/env python3
"""
Generate IDA script to fix all void*/char* this parameters to proper class types.

Scans asm/pal3/decomp/*.json for __thiscall functions where the this parameter
has wrong type (void* or char* instead of ClassName*), and generates an IDA
script that sets correct signatures.

Usage:
  python tools/gen_ida_fix_this_types.py
"""

import json
import os
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent
DECOMP_DIR = PROJECT_ROOT / "asm" / "pal3" / "decomp"
OUTPUT_SCRIPT = PROJECT_ROOT / "tools" / "ida" / "pal3_fix_this_types2.py"


def parse_and_fix(decomp_dir):
    """Find all functions with wrong this type and generate fixes."""
    fixes = []

    for f in sorted(decomp_dir.glob("*.json")):
        if f.name.startswith("_"):
            continue
        try:
            with open(f, 'r', encoding='utf-8') as fh:
                d = json.load(fh)
        except:
            continue

        sig = d.get('signature', '')
        name = d.get('name', '')
        addr = d.get('address', '')

        if '::' not in name or name.startswith('sub_'):
            continue

        # Check for wrong this types
        has_wrong_this = False
        if re.search(r'void \*\s*this', sig):
            has_wrong_this = True
        elif re.search(r'char \*\s*this', sig):
            has_wrong_this = True

        if not has_wrong_this:
            continue

        # Extract class name
        m = re.match(r'(\w+)::', name)
        if not m:
            continue
        cls = m.group(1)

        # Clean the function name (remove parameter list from IDA name if present)
        clean_name = name.split('(')[0] if '(' in name else name

        # Fix the signature: replace wrong this type with ClassName*
        new_sig = re.sub(r'(void|char) \*\s*this', f'{cls} *this', sig)

        # Build full IDA-compatible signature
        # Input formats from IDA:
        #   "ret __thiscall(params)"      e.g. "int __thiscall(Actor *this, int x)"
        #   "ret *__thiscall(params)"     e.g. "void *__thiscall(Actor *this)"
        #   "ret(params)"                 e.g. "char *(Actor *this, char *fmt)"
        # We need to extract: return_type, calling_convention, params
        # Then build: "ret cc ClassName::Method(params)"

        # Strategy: find the calling convention keyword, split around it
        cc_match = re.search(r'(__thiscall|__cdecl|__stdcall|__fastcall)', new_sig)
        paren_match = re.search(r'\(', new_sig)

        if cc_match and paren_match:
            cc = cc_match.group(1)
            cc_start = cc_match.start()
            cc_end = cc_match.end()
            paren_pos = paren_match.start()

            # Return type is everything before the cc keyword
            # But handle "void *__thiscall" where * is adjacent
            ret_part = new_sig[:cc_start].rstrip()
            # If ret_part ends with nothing (cc at start), default
            if not ret_part:
                ret_part = 'int'

            # Params are inside the parens
            params = new_sig[paren_pos+1:new_sig.rfind(')')]

            full_sig = f'{ret_part} {cc} {clean_name}({params})'
        elif paren_match:
            # No calling convention found, assume __thiscall
            paren_pos = paren_match.start()
            ret_part = new_sig[:paren_pos].rstrip()
            if not ret_part:
                ret_part = 'int'
            params = new_sig[paren_pos+1:new_sig.rfind(')')]
            full_sig = f'{ret_part} __thiscall {clean_name}({params})'
        else:
            continue

        fixes.append((addr, clean_name, full_sig))

    return fixes


def generate_ida_script(fixes, output_path):
    """Generate IDAPython script."""
    lines = []
    lines.append('"""')
    lines.append(f'IDAPython: Fix this-pointer types for {len(fixes)} functions.')
    lines.append('Generated by tools/gen_ida_fix_this_types.py')
    lines.append('"""')
    lines.append('import ida_auto, ida_name, idc, os')
    lines.append('')
    lines.append('SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))')
    lines.append('LOG_DIR = os.path.join(SCRIPT_DIR, "_logs")')
    lines.append('LOG_FILE = os.path.join(LOG_DIR, "pal3_fix_this_types2_log.txt")')
    lines.append('')
    lines.append('log_lines = []')
    lines.append('def log(msg):')
    lines.append('    log_lines.append(str(msg))')
    lines.append('    print(msg)')
    lines.append('')
    lines.append('FIXES = [')
    for addr, name, sig in sorted(fixes, key=lambda x: int(x[0], 16)):
        # Escape backslashes and quotes in sig
        sig_escaped = sig.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    ({addr}, "{name}",')
        lines.append(f'     "{sig_escaped}"),')
    lines.append(']')
    lines.append('')
    lines.append('def main():')
    lines.append('    try:')
    lines.append('        ida_auto.auto_wait()')
    lines.append(f'        log("[*] Fixing this-pointer types for %d functions" % len(FIXES))')
    lines.append('        fixed = 0')
    lines.append('        for addr, name, sig in FIXES:')
    lines.append('            if idc.SetType(addr, sig):')
    lines.append('                fixed += 1')
    lines.append('                log("  [+] 0x%08X: %s" % (addr, name))')
    lines.append('            else:')
    lines.append('                log("  [-] 0x%08X: FAILED %s" % (addr, sig))')
    lines.append('        log("[*] Fixed: %d / %d" % (fixed, len(FIXES)))')
    lines.append('        ida_auto.auto_wait()')
    lines.append('        idc.save_database(idc.get_idb_path(), 0)')
    lines.append('        log("[*] Done")')
    lines.append('    except Exception as e:')
    lines.append('        log("[!] %s" % str(e))')
    lines.append('    os.makedirs(LOG_DIR, exist_ok=True)')
    lines.append('    with open(LOG_FILE, "w", encoding="utf-8") as f:')
    lines.append('        f.write("\\n".join(log_lines))')
    lines.append('    idc.qexit(0)')
    lines.append('')
    lines.append("if __name__ == '__main__':")
    lines.append('    main()')
    lines.append('')

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))


def main():
    fixes = parse_and_fix(DECOMP_DIR)
    print(f"Found {len(fixes)} functions with wrong this-pointer types:")
    print()

    # Group by class for summary
    by_class = {}
    for addr, name, sig in fixes:
        cls = name.split('::')[0]
        by_class.setdefault(cls, []).append((addr, name, sig))

    for cls in sorted(by_class.keys()):
        methods = by_class[cls]
        print(f"  {cls}: {len(methods)} methods")

    print()
    generate_ida_script(fixes, OUTPUT_SCRIPT)
    print(f"Generated IDA script: {OUTPUT_SCRIPT}")
    print(f"Run in IDA: idat64.exe -A -S\"{OUTPUT_SCRIPT}\" PAL3.exe.i64")


if __name__ == '__main__':
    main()

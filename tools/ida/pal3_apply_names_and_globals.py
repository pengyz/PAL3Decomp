def main():
    try:
        ida_auto.auto_wait()
        log("[*] Applying function names + global variable types")

        # Phase 1: Function names
        named = 0
        for addr, name in FUNC_NAMES:
            if ida_name.set_name(addr, name, ida_name.SN_NOWARN | ida_name.SN_FORCE):
                named += 1
        log("[*] Function names: %d / %d applied" % (named, len(FUNC_NAMES)))

        # Phase 2: Global variable types
        til = ida_typeinf.get_idati()
        typed = 0
        for addr, name, type_str in GLOBAL_TYPES:
            # Set name
            ida_name.set_name(addr, name, ida_name.SN_NOWARN | ida_name.SN_FORCE)
            # Set type
            tif = ida_typeinf.tinfo_t()
            decl = "%s %s;" % (type_str, name)
            if ida_typeinf.parse_decl(tif, til, decl, ida_typeinf.PT_VAR) is not None:
                if ida_typeinf.apply_tinfo(addr, tif, ida_typeinf.TINFO_DEFINITE):
                    typed += 1
                    log("  [+] 0x%08X: %s %s" % (addr, type_str, name))
                else:
                    log("  [-] 0x%08X: apply failed for %s" % (addr, name))
            else:
                log("  [-] 0x%08X: parse failed for '%s'" % (addr, decl))
        log("[*] Global types: %d / %d applied" % (typed, len(GLOBAL_TYPES)))

        ida_auto.auto_wait()
        idc.save_database(idc.get_idb_path(), 0)
        log("[*] Saved. Done.")

    except Exception as e:
        import traceback
        log("[!] %s" % str(e))
        log(traceback.format_exc())

    os.makedirs(LOG_DIR, exist_ok=True)
    with open(LOG_FILE, 'w', encoding='utf-8') as f:
        f.write("\n".join(log_lines))
    idc.qexit(0)


"""
IDAPython: 导出全局变量信息

从 IDA 数据库扫描 .data/.rdata/.bss 段中所有已命名的全局变量,
输出为 JSON 供后续源码生成使用。

输出:
  - asm/pal3a/globals_export.json

用法:
  idat.exe -A -S"ida_export_globals.py" PAL3A.exe.i64
"""

import ida_auto
import ida_bytes
import ida_funcs
import ida_name
import ida_segment
import idautils
import idc
import json
import os
import sys
import time
import traceback
import builtins

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
LOG_DIR = os.path.join(SCRIPT_DIR, "_logs")
LOG_FILE = os.path.join(LOG_DIR, "ida_export_globals.log")
OUTPUT_FILE = os.path.join(PROJECT_ROOT, "asm", "pal3a", "globals_export.json")

# Segments to scan
RDATA_START = 0x0056A000
RDATA_END = 0x0057F1F2
DATA_START = 0x00580000
DATA_END = 0x0060C000

# Names to skip (auto-generated by IDA)
SKIP_PREFIXES = (
    'sub_', 'loc_', 'off_', 'unk_', 'byte_', 'word_',
    'dword_', 'qword_', 'flt_', 'stru_', 'algn_',
    'nullsub_', 'j_', 'locret_',
)


def main():
    log_lines = []

    def log(msg):
        log_lines.append(str(msg))
        print(msg)

    try:
        ida_auto.auto_wait()
        log("[*] PAL3A Global Variable Export")
        log(f"[*] Time: {time.strftime('%Y-%m-%d %H:%M:%S')}")

        globals_list = []
        class_statics = []

        # Scan all named addresses in data segments
        for ea, name in idautils.Names():
            # Check if in data/rdata segment
            in_rdata = RDATA_START <= ea < RDATA_END
            in_data = DATA_START <= ea < DATA_END
            if not (in_rdata or in_data):
                continue

            # Skip function entries
            if ida_funcs.get_func(ea):
                continue

            # Skip auto-generated names
            if name.startswith(SKIP_PREFIXES):
                continue

            # Get type and size info
            type_str = idc.get_type(ea) or ""
            size = idc.get_item_size(ea)
            segment = "rdata" if in_rdata else "data"

            # Determine if it's a class static member (contains ::)
            is_class_static = '::' in name

            entry = {
                'address': f"0x{ea:08X}",
                'name': name,
                'type': type_str,
                'size': size,
                'segment': segment,
            }

            if is_class_static:
                # Parse class name
                parts = name.split('::')
                entry['class'] = parts[0]
                entry['member'] = '::'.join(parts[1:])
                class_statics.append(entry)
            else:
                globals_list.append(entry)

        # Also scan for vtables (??_7 prefix in mangled names, or vftable)
        vtables = []
        for ea, name in idautils.Names():
            if RDATA_START <= ea < RDATA_END:
                if '??_7' in name or 'vftable' in name.lower():
                    vtables.append({
                        'address': f"0x{ea:08X}",
                        'name': name,
                        'size': idc.get_item_size(ea),
                    })

        log(f"  Global variables: {len(globals_list)}")
        log(f"  Class statics: {len(class_statics)}")
        log(f"  VTables: {len(vtables)}")

        # Write output
        os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
        result = {
            'meta': {
                'timestamp': time.strftime('%Y-%m-%dT%H:%M:%S'),
                'total_globals': len(globals_list),
                'total_class_statics': len(class_statics),
                'total_vtables': len(vtables),
            },
            'globals': globals_list,
            'class_statics': class_statics,
            'vtables': vtables,
        }

        with open(OUTPUT_FILE, 'w', encoding='utf-8') as f:
            json.dump(result, f, indent=2, ensure_ascii=False)

        log(f"[+] Output: {OUTPUT_FILE}")

    except Exception as e:
        log(f"[!] ERROR: {e}")
        log(traceback.format_exc())

    os.makedirs(LOG_DIR, exist_ok=True)
    with open(LOG_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(log_lines))

    if not getattr(builtins, '_IDA_PIPELINE_RUNNING', False):
        try:
            idc.qexit(0)
        except:
            pass


if __name__ == '__main__':
    main()

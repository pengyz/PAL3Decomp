"""
Generate pal3a_types.h with forward declarations, enums, and basic types.
Classes are defined in per-file stub headers (generated by pal3a_generate_stubs.py).
"""
import json
import re

INPUT = "asm/pal3a/pdb_export.json"
OUTPUT = "src/pal3a/pal3a_types.h"

WINDOWS_TYPES = {
    'tagPOINT', 'tagRECT', 'tagRGBQUAD', 'tagMSG', 'tagSIZE',
    'POINT', 'RECT', 'SIZE', 'RGBQUAD', 'MSG',
}


def main():
    with open(INPUT) as f:
        data = json.load(f)

    classes = data['classes']
    enums = data.get('enums', [])

    class_names = sorted(set(cls['name'] for cls in classes
                            if '::' not in cls['name'] and '<' not in cls['name'] and ' ' not in cls['name']))

    # Collect class names that will be generated by stub generator (PAL3A source with .cpp)
    stub_generated_classes = set()
    for func in data['functions']:
        src = func.get('source_file', '')
        if not src or 'PAL3A' not in src or '.cpp' not in src.lower():
            continue
        cls_name = func.get('class', '')
        if cls_name and '::' not in cls_name and '<' not in cls_name and ' ' not in cls_name:
            stub_generated_classes.add(cls_name)
        elif '::' in func.get('name', ''):
            parts = func['name'].rsplit('::', 1)
            cn = parts[0]
            if '::' not in cn and '<' not in cn and ' ' not in cn:
                stub_generated_classes.add(cn)

    # Collect types referenced by PAL3A
    pal3a_funcs = [f for f in data['functions']
                   if f.get('source_file', '') and 'PAL3A' in f.get('source_file', '')]
    all_types_used = set()
    for func in pal3a_funcs:
        for p in func.get('parameters', []):
            if p.get('type'):
                all_types_used.add(p['type'])
        if func.get('return_type'):
            all_types_used.add(func['return_type'])
    for cls in classes:
        for m in cls.get('data_members', []):
            all_types_used.add(m['type'])

    # Tag types
    tag_types = set()
    for t in all_types_used:
        for m in re.findall(r'\btag\w+', t):
            if m not in WINDOWS_TYPES:
                tag_types.add(m)

    # Enums referenced
    enum_names_all = set(e['name'] for e in enums)
    used_enums = set()
    for t in all_types_used:
        for en in enum_names_all:
            if en in t:
                used_enums.add(en)

    # === Generate ===
    lines = []
    lines.append("#ifndef PAL3A_TYPES_H")
    lines.append("#define PAL3A_TYPES_H")
    lines.append("")
    lines.append("#include <windows.h>")
    lines.append("#include <vector>")
    lines.append("#include <string>")
    lines.append("#include <map>")
    lines.append("")

    lines.append("// D3DX stub types")
    lines.append("struct D3DXVECTOR2 { float x, y; };")
    lines.append("struct D3DXVECTOR3 { float x, y, z; };")
    lines.append("struct D3DXVECTOR4 { float x, y, z, w; };")
    lines.append("struct D3DXMATRIX { float m[4][4]; };")
    lines.append("struct D3DXQUATERNION { float x, y, z, w; };")
    lines.append("struct D3DXCOLOR { float r, g, b, a; };")
    lines.append("struct D3DXPLANE { float a, b, c, d; };")
    lines.append("typedef struct IDirect3DDevice9* LPDIRECT3DDEVICE9;")
    lines.append("typedef struct IDirect3DTexture9* LPDIRECT3DTEXTURE9;")
    lines.append("typedef struct IDirect3DVertexBuffer9* LPDIRECT3DVERTEXBUFFER9;")
    lines.append("typedef struct IDirect3DIndexBuffer9* LPDIRECT3DINDEXBUFFER9;")
    lines.append("typedef struct IDirect3DSurface9* LPDIRECT3DSURFACE9;")
    lines.append("")

    lines.append("// gbengine math types")
    lines.append("typedef D3DXVECTOR2 gbVec2D;")
    lines.append("typedef D3DXVECTOR3 gbVec3D;")
    lines.append("typedef D3DXVECTOR4 gbVec4D;")
    lines.append("typedef D3DXMATRIX gbMatrix4;")
    lines.append("typedef D3DXQUATERNION gbQuaternion;")
    lines.append("typedef D3DXCOLOR gbColorFlt;")
    lines.append("typedef D3DXPLANE gbPlane;")
    lines.append("struct gbColorQuad { unsigned char b, g, r, a; };")
    lines.append("")

    lines.append("typedef unsigned long ulong;")
    lines.append("typedef unsigned int uint;")
    lines.append("typedef unsigned short ushort;")
    lines.append("typedef unsigned char uchar;")
    lines.append("")

    lines.append("struct gbOBBox { gbVec3D center; gbVec3D axis[3]; gbVec3D extent; };")
    lines.append("struct gbAABBox { gbVec3D vMin; gbVec3D vMax; };")
    lines.append("struct gbSphere { gbVec3D center; float radius; };")
    lines.append("struct gbRay { gbVec3D origin; gbVec3D direction; };")
    lines.append("")

    # gbengine forward declarations
    gb_forward = sorted({
        'gbGfxManager', 'gbGfxManager_D3D', 'gbActor', 'gbCamera', 'gbScene',
        'gbSceneNode', 'gbTexture', 'gbMesh', 'gbVFileSystem', 'gbVFile',
        'gbImage2D', 'gbMatrixStack', 'gbRenderEffect', 'gbPrintFont',
        'gbPrintFontMgr', 'gbLight', 'gbLightMgr', 'gbDynVertBuf',
        'gbAnimNodeGroup', 'gbBinkVideo', 'gbUIQuad', 'gbTextureArray',
        'gbRenderInfoObj', 'gbSurfaceDesc', 'gbPixelFmtDesc',
        'gbResManager', 'gbResMgr', 'gbResource', 'gbSceneRender',
        'gbD3DFontManager', 'gbGameTimer', 'gbInputManager', 'gbSoundManager',
    })
    lines.append("// gbengine forward declarations")
    for gb in gb_forward:
        lines.append(f"class {gb};")
    lines.append("")

    # Tag structs
    lines.append("// Game tag structs")
    for tag in sorted(tag_types):
        lines.append(f"struct {tag} {{ int _stub; }};")
    lines.append("")

    # Enums
    lines.append("// Game enums")
    emitted_enums = set()
    for enum in sorted(enums, key=lambda e: e['name']):
        ename = enum['name']
        if '::' in ename or ename.startswith('__') or ' ' in ename:
            continue
        if ename not in used_enums:
            continue
        if ename in emitted_enums:
            continue
        emitted_enums.add(ename)
        members = enum.get('members', [])
        if not members:
            lines.append(f"enum {ename} {{ {ename}_STUB = 0 }};")
        else:
            lines.append(f"enum {ename} {{")
            for i, m in enumerate(members):
                mname = m['name']
                mval = m.get('value', i)
                comma = ',' if i < len(members) - 1 else ''
                lines.append(f"    {mname} = {mval}{comma}")
            lines.append("};")
    lines.append("")

    # External types
    lines.append("// External library types")
    lines.append("struct BINK { int _stub; };")
    lines.append("struct CPK { char _data[256]; };")
    lines.append("struct HSAMPLE { int _stub; };")
    lines.append("struct HDIGDRIVER { int _stub; };")
    # _PlugInfo is defined in ui/UIPlugInfo.h as a class
    lines.append("")

    # Template types
    lines.append("template<int N, int M, class T> struct matrix { T data[N*M]; };")
    lines.append("template<int N, class T> struct primitive { T data[N]; };")
    lines.append("template<int N, class T> struct Collide_Ray { T origin[N]; T direction[N]; };")
    lines.append("template<class T> class SubTask { public: int _stub; };")
    lines.append("template<class T1, class T2> class CTaskTpl { public: int _stub; };")
    lines.append("")

    # Collect ALL unique identifiers used as types in function parameters/returns
    # These need to be forward-declared or defined
    basic_set = {'int', 'char', 'float', 'double', 'bool', 'void', 'long', 'short',
                 'unsigned int', 'unsigned long', 'unsigned short', 'unsigned char',
                 '__int64', 'BOOL', 'BYTE', 'WORD', 'DWORD', 'UINT', 'LONG', 'HRESULT',
                 'ulong', 'uint', 'ushort', 'uchar', 'HWND', 'HANDLE', 'LPARAM', 'WPARAM',
                 'LRESULT', 'HDC', 'HINSTANCE', 'HMENU', 'HBITMAP', 'HICON', 'HBRUSH',
                 'HFONT', 'HPEN', 'HRGN', 'HPALETTE', 'HKEY', 'LPCSTR', 'LPSTR', 'LPVOID'}
    windows_internal = {'HWND__', 'HINSTANCE__', 'HDC__', 'HBITMAP__', 'HMENU__',
                       'HICON__', 'HBRUSH__', 'HFONT__', 'HPEN__', 'HRGN__',
                       'HPALETTE__', 'HKEY__', '_iobuf', '_FILETIME', '_EXCEPTION_POINTERS',
                       '_EXCEPTION_RECORD', '_CONTEXT', '_SECURITY_ATTRIBUTES',
                       '_OVERLAPPED', '_GUID', '_LARGE_INTEGER', '_ULARGE_INTEGER',
                       '_WIN32_FIND_DATAA', '_SYSTEMTIME', '_MEMORYSTATUS'}
    already_defined = set(class_names) | stub_generated_classes | set(gb_forward) | set(tag_types) | emitted_enums | \
                      WINDOWS_TYPES | basic_set | windows_internal | \
                      {'BINK', 'CPK', 'HSAMPLE', 'HDIGDRIVER', '_PlugInfo',
                       'gbVec2D', 'gbVec3D', 'gbVec4D', 'gbMatrix4', 'gbQuaternion',
                       'gbColorFlt', 'gbPlane', 'gbColorQuad', 'gbOBBox', 'gbAABBox',
                       'gbSphere', 'gbRay', 'D3DXVECTOR2', 'D3DXVECTOR3', 'D3DXVECTOR4',
                       'D3DXMATRIX', 'D3DXQUATERNION', 'D3DXCOLOR', 'D3DXPLANE'}
    keywords = {'unsigned', 'signed', 'const', 'volatile', 'static', 'extern',
                'virtual', 'inline', 'register', 'auto', 'class', 'struct', 'enum',
                'union', 'typedef', 'return', 'if', 'else', 'while', 'for', 'do',
                'switch', 'case', 'break', 'continue', 'goto', 'default', 'sizeof',
                'new', 'delete', 'this', 'true', 'false', 'NULL', 'nullptr'}
    extra_types = set()
    for t in all_types_used:
        # Extract base type (strip pointer, ref, const, array, prefixes)
        clean = t.replace('const ', '').replace(' const', '').replace('*', '').replace('&', '')
        clean = re.sub(r'\[.*?\]', '', clean).strip()
        for prefix in ('struct ', 'class ', 'enum ', 'virtual '):
            if clean.startswith(prefix):
                clean = clean[len(prefix):]
                break
        # Skip basic types, template types, std types, keywords
        if not clean or clean in already_defined or clean in keywords:
            continue
        if clean.startswith('std::') or '<' in clean or '::' in clean:
            continue
        if clean[0].isdigit() or ' ' in clean:
            continue
        # Skip Windows internal types (start with _ followed by uppercase)
        if clean.startswith('_') and len(clean) > 1 and clean[1].isupper():
            continue
        # Skip types ending with __ (Windows handles)
        if clean.endswith('__'):
            continue
        extra_types.add(clean)

    # Forward declarations for ALL classes from PDB + stub-generated classes
    lines.append("// PAL3A class forward declarations")
    all_forward_classes = sorted(set(class_names) | stub_generated_classes)
    for cname in all_forward_classes:
        if cname in set(gb_forward):
            continue
        lines.append(f"class {cname};")
    lines.append("")

    # Define additional types used in parameters as stub structs
    # (forward declarations aren't enough when used by value or as return types)
    if extra_types:
        lines.append("// Additional types referenced in function signatures")
        for t in sorted(extra_types):
            lines.append(f"struct {t} {{ char _data[4]; }};")
        lines.append("")

    lines.append("#endif // PAL3A_TYPES_H")
    lines.append("")

    with open(OUTPUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    print(f"Generated {OUTPUT}: {len(lines)} lines")
    print(f"  Forward-declared classes: {len(class_names)}")
    print(f"  Enums: {len(emitted_enums)}")
    print(f"  Tag structs: {len(tag_types)}")


if __name__ == "__main__":
    main()
